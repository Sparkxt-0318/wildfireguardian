# ---------------------------------------------------------------------------------------------- wfgvu.synth adapter
def synth_b_nothing(root, distance_m: float = 3.0, n_runs: int = 3, seed: int = 7, duration_s: float = 15.0,
                    **kw) -> List[Path]:
    """Test B 'nothing' runs generated by wfgvu.synth's `corner_reflector` scenario (SIMULATED; synth's own stated
    toy physics), wrapped with the trial.json and marks.jsonl that b_radar_analyse needs. The first run is the
    baseline. synth has no flame/smoke/mist overlay at the reflector, so only the 'nothing' condition can come from
    it; the other conditions come from sim_b. Raises ImportError if wfgvu.synth is absent."""
    from wfgvu import synth
    root = Path(root)
    params = dict(range_m=float(distance_m), n_bins=128, range_res_m=0.0488, thermal_hz=0.5, gnss_hz=1.0)
    params.update(kw)
    out = []
    for i in range(n_runs):
        d = synth.generate("corner_reflector", root / ("B_d%.1f_nothing_%s_r%d_SYNTH" % (
            distance_m, "baseline" if i == 0 else "trial", i + 1)), seed=seed + i, duration=duration_s, **params)
        info = json.loads((d / "session.json").read_text())
        t0, t1 = float(info["t_mono_first"]), float(info["t_mono_last"])
        role = "baseline" if i == 0 else "trial"
        marks = ([("baseline", t0 + 0.5), ("end", t1 - 0.2)] if role == "baseline"
                 else [("pre", t0 + 0.2), ("condition_on", t0 + 0.5), ("condition_off", t1 - 0.2), ("end", t1)])
        with open(d / "marks.jsonl", "w") as fh:
            for k, t in marks:
                fh.write(json.dumps({"t_rx": t + RX_OFFSET, "pi_t_mono": t, "kind": k, "note": "SYNTH"}) + "\n")
        common.write_json(d / "trial.json", {"test": "B", "run_id": d.name, "distance_m": float(distance_m),
                                             "condition": "nothing", "role": role, "repeat": i + 1,
                                             "flame_distance_m": float(distance_m) / 2, "simulated": True,
                                             "generator": "wfgvu.synth corner_reflector", "created_utc": "SYN-%d" % i})
        out.append(d)
    return out
