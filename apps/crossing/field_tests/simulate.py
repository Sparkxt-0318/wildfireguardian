def _thumb() -> dict:
    global _THUMB
    if _THUMB is None:
        _THUMB = protocol.encode_thermal(np.full((6, 8), 290.0) + np.arange(48).reshape(6, 8) * 0.1)
    return _THUMB


def _unit_stream(run: SimRun, rng, t0: float, t1: float, env: Callable[[float], dict],
                 radar_gap: Sequence[Tuple[float, float, str]] = (), tc_air_fault: Sequence[Tuple[float, float]] = (),
                 gnss_fn: Optional[Callable[[float], dict]] = None) -> None:
    """Readings for all eight sensors at SIM_RATES. env(t) -> {cpu, housing, air, plate, uv}. radar_gap entries
    (a, b, mode): no radar readings in [a, b); mode "no_device" = heartbeats admit it, "silent" = heartbeats keep
    saying ok (the failure test F must catch)."""
    def in_gap(t, gl):
        return any(a <= t < b for a, b, *_ in gl)
    for s, hz in SIM_RATES.items():
        for t in np.arange(t0, t1, 1.0 / hz):
            t = float(t)
            e = env(t)
            if s == "thermal":
                run.reading(s, t, _thumb())
            elif s == "radar":
                if in_gap(t, radar_gap):
                    continue
                prof = [round(float(v), 2) for v in 30 + 5 * np.sin(np.arange(16)) + rng.normal(0, 0.5, 16)]
                run.reading(s, t, {"frame": run.seq.get(s, 0), "range_res_m": 0.0488, "n_bins": 16,
                                   "range_profile_db": prof, "az_heatmap": None, "points": None,
                                   "tlv_types": [2], "frame_ok": True})
            elif s in ("tc_plate", "tc_housing", "tc_air"):
                key = {"tc_plate": "plate", "tc_housing": "housing", "tc_air": "air"}[s]
                if s == "tc_air" and in_gap(t, [(a, b) for a, b in tc_air_fault]):
                    run.reading(s, t, tc_data(None, e["housing"], "open"))
                else:
                    run.reading(s, t, tc_data(e[key] + rng.normal(0, 0.1), e["housing"]))
            elif s == "imu":
                run.reading(s, t, {"roll_deg": rng.normal(0, 0.8), "pitch_deg": rng.normal(0, 0.8),
                                   "heading_deg": e.get("course", 0.0), "grav": [0.0, 0.0, 9.81],
                                   "calib": {"sys": 3, "gyro": 3, "accel": 3, "mag": 2}})
            elif s == "gnss":
                g = gnss_fn(t) if gnss_fn else {"fix": 1, "lat": 36.6, "lon": 126.66, "alt_m": 40.0,
                                                "speed_m_s": 0.0, "course_deg": None, "hdop": 0.9, "sats": 9}
                g.setdefault("utc", None)
                run.reading(s, t, g)
            elif s == "pi":
                uv = bool(e.get("uv"))
                run.reading(s, t, {"cpu_c": round(e["cpu"] + rng.normal(0, 0.5), 1),
                                   "throttled_hex": "0x50005" if uv else ("0x50000" if e.get("uv_ever") else "0x0"),
                                   "under_voltage_now": uv, "under_voltage_ever": bool(e.get("uv_ever") or uv),
                                   "input_v": None, "disk_free_mb": 20000.0 - (t - t0) * 1.5,
                                   "rec_bytes": int((t - t0) * 1.6e6)})

    def hb_status(s, t):
        for a, b, mode in radar_gap:
            if s == "radar" and a <= t < b and mode == "no_device":
                return "no_device", "read error, retrying"
        if s == "tc_air" and any(a <= t < b + 0.5 for a, b in tc_air_fault):
            return "error", "fault open"
        return "ok", ""
    run.heartbeats_every(list(SIM_RATES), t0, t1, 0.5, hb_status)
    run.event(t0 + 0.2, "radar_config_sent", "config/iwr6843aop_vu.cfg (SIMULATED)")
    for a, b, mode in radar_gap:
        if mode == "no_device":
            run.event(b + 0.1, "sensor_reconnected", "radar")


def _laptop_copy(run_dir: Path, pi_run: SimRun, drops: Sequence[Tuple[float, float]], trial: dict,
                 marks: Sequence[dict] = (), guard: Optional[dict] = None) -> Path:
    """Laptop copy: the Pi messages minus those sent during link dropouts, with rx receipt lines and
    disconnect/connect link lines for dropouts longer than 2 s (websocket ping timeout). `guard` = kwargs for
    apply_disc_guard (the record script's disc guard runs on what reached the laptop)."""
    lap = SimRun(run_dir, pi_run.ctx.session_id)
    keep = [m for m in pi_run.msgs if not any(a <= m["t_mono"] < b for a, b in drops)]
    lap.msgs = keep
    lap.marks = list(marks)
    if guard is not None:
        trial = dict(trial)
        apply_disc_guard(lap, **guard).annotate(trial)
    for a, b in drops:
        if b - a > 2.0:
            lap.rx_lines.append({"t_rx": a + 2.0 + RX_OFFSET, "link": "disconnect", "detail": "ping timeout (SIM)"})
            lap.rx_lines.append({"t_rx": b + RX_OFFSET, "link": "connect", "detail": "SIM"})
    d = lap.write(trial, rx_from_msgs=True, info_extra={"config": SIM_CONFIG,
                                                         "recorded_by": "laptop copy (SIMULATED)"})
    return d


def sim_e(root, seed: int = 5, duration_s: float = 1800.0) -> Dict[str, Path]:
    """SIMULATED test E drive: 30 min, synthetic track near 36.60 N 126.66 E (not a real route), mostly 8-16 m/s
    with stops; GNSS 1 Hz with a 40 s no-fix underpass and a stretch of poor hdop under trees; engine-crank
    under-voltage for 2 s at the start; CPU 55 -> 68 C, housing 25 -> 38 C (sun), air 22 -> 27 C; a 0.3 s tc_air
    open fault; a 3.5 s radar USB reconnect (no_device); laptop link dropouts of 1.4 s, 4.5 s and 0.8 s."""
    rng = np.random.default_rng(seed)
    root = Path(root)
    t0 = 20000.0
    t1 = t0 + duration_s
    f = duration_s / 1800.0
    # track: integrate speed and heading at 1 Hz
    ts = np.arange(t0, t1, 1.0)
    v = np.clip(12 + 4 * np.sin((ts - t0) / 97.0) + rng.normal(0, 0.5, ts.size), 0, 17)
    v[(ts - t0) < 30 * f] = 0.0
    for stop in (400, 1100, 1500):
        v[np.abs(ts - t0 - stop * f) < 15 * f] = 0.0
    turn = np.zeros(ts.size)
    for a, rate in ((200, 1.5), (520, -1.0), (800, 2.0), (1250, -1.8), (1600, 1.2)):
        turn[(ts - t0 >= a * f) & (ts - t0 < (a + 60) * f)] = rate
    course = (35.0 + np.cumsum(turn)) % 360.0
    e_m = np.cumsum(v * np.sin(np.radians(course)))
    n_m = np.cumsum(v * np.cos(np.radians(course)))
    lat = 36.60 + n_m / 111195.0
    lon = 126.66 + e_m / (111195.0 * math.cos(math.radians(36.60)))
    nofix = (t0 + 600 * f, t0 + 600 * f + 40)
    trees = (t0 + 1200 * f, t0 + 1300 * f)

    def gnss_fn(t):
        i = min(int(t - t0), ts.size - 1)
        if nofix[0] <= t < nofix[1]:
            return {"fix": 0, "lat": None, "lon": None, "alt_m": None, "speed_m_s": None, "course_deg": None,
                    "hdop": None, "sats": 3}
        poor = trees[0] <= t < trees[1]
        hd = float(np.clip(2.5 + abs(rng.normal(0, 0.8)), 1.5, 6) if poor else 0.8 + abs(rng.normal(0, 0.2)))
        jit = 3.0 if poor else 0.8
        return {"fix": 1 if (poor or rng.random() < 0.7) else 2, "lat": float(lat[i] + rng.normal(0, jit) / 111195),
                "lon": float(lon[i] + rng.normal(0, jit) / 89000), "alt_m": 40.0 + rng.normal(0, 1),
                "speed_m_s": float(v[i]), "course_deg": float(course[i]), "hdop": round(hd, 2),
                "sats": int(5 if poor else rng.integers(8, 13))}

    def env(t):
        x = (t - t0) / duration_s
        i = min(int(t - t0), ts.size - 1)
        return {"cpu": 55 + 13 * x, "housing": 25 + 13 * x, "air": 22 + 5 * x, "plate": 26 + 14 * x,
                "uv": t0 + 5 <= t < t0 + 7, "uv_ever": t >= t0 + 5, "course": float(course[i])}
    pi = SimRun(root / "pi_session_VU-SIM-E", "VU-SIM-E-drive")
    _unit_stream(pi, rng, t0, t1, env, radar_gap=[(t0 + 1500 * f, t0 + 1500 * f + 3.5, "no_device")],
                 tc_air_fault=[(t0 + 900 * f, t0 + 900 * f + 0.3)], gnss_fn=gnss_fn)
    pi_dir = pi.write(None, info_extra={"config": SIM_CONFIG})
    write_unit_heartbeats(pi_dir, pi.ctx.session_id, t0, t1)
    drops = [(t0 + 300 * f, t0 + 300 * f + 1.4), (t0 + 1010 * f, t0 + 1010 * f + 4.5), (t0 + 1650 * f, t0 + 1650 * f + 0.8)]
    lap = _laptop_copy(root / "E_drive_SIM", pi, drops, {"test": "E", "run_id": "E_drive_SIM",
                                                        "vehicle": "SIMULATED car", "duration_s": duration_s},
                       [{"t_rx": t0 + 1 + RX_OFFSET, "pi_t_mono": t0 + 1, "kind": "drive", "note": "SIM"}])
    return {"pi": pi_dir, "laptop": lap}


F_PHASES = (("baseline", 120.0, "Unit running dry, nothing applied"),
            ("spray", 300.0, "Water spray on all faces (garden-hose spray nozzle)"),
            ("dry", 60.0, "Spray off"),
            ("hot_air_front", 240.0, "Hot-air gun on the front face and the shield"),
            ("hot_air_plate", 120.0, "Hot-air gun on the flux plate"),
            ("hot_air_probe", 120.0, "Hot-air gun on the air probe"),
            ("cool", 60.0, "Hot-air gun off"))


def sim_f(root, seed: int = 6, scale: float = 1.0) -> Dict[str, Path]:
    """SIMULATED test F (water spray + hot-air gun): housing 24 -> 47 C during the hot-air phases, CPU 52 -> 74 C,
    plate pulse to about 60 C during hot_air_plate (the protocol keeps the disc under its 70 C limit: copper on PETG
    tabs; the record script's disc guard runs on the laptop copy and does not fire), air to 60 C during
    hot_air_probe. Deliberate faults so the checks are
    exercised: radar readings stop for 2.5 s during hot_air_front while its heartbeats keep saying "ok" (a silent
    stop), and a 3.2 s laptop link dropout during the spray."""
    rng = np.random.default_rng(seed)
    root = Path(root)
    t0 = 40000.0
    bounds, t = [], t0 + 2.0
    for kind, dur, text in F_PHASES:
        bounds.append((kind, t, t + dur * scale, text))
        t += dur * scale
    t1 = t + 1.0
    ph = {k: (a, b) for k, a, b, _ in bounds}

    def ramp(t, a, b, lo, hi, tau):
        if t < a:
            return lo
        x = 1 - math.exp(-(min(t, b) - a) / tau)
        v = lo + (hi - lo) * x
        if t > b:
            v = lo + (v - lo) * math.exp(-(t - b) / tau)
        return v

    def env(t):
        a, b = ph["hot_air_front"]
        housing = ramp(t, a, b, 24.0, 49.0, 150.0 * scale)
        cpu = 52 + (housing - 24) * 0.9
        pa, pb = ph["hot_air_plate"]
        plate = ramp(t, pa, pb, 24.0, 62.0, 40.0 * scale)
        qa, qb = ph["hot_air_probe"]
        air = ramp(t, qa, qb, 22.0, 62.0, 30.0 * scale)
        return {"cpu": cpu, "housing": housing, "air": air, "plate": plate, "uv": False, "uv_ever": False}
    a, b = ph["hot_air_front"]
    pi = SimRun(root / "pi_session_VU-SIM-F", "VU-SIM-F-housing")
    _unit_stream(pi, rng, t0, t1, env, radar_gap=[(a + 60 * scale, a + 60 * scale + 2.5, "silent")])
    pi_dir = pi.write(None, info_extra={"config": SIM_CONFIG})
    write_unit_heartbeats(pi_dir, pi.ctx.session_id, t0, t1)
    sa, _ = ph["spray"]
    drops = [(sa + 100 * scale, sa + 100 * scale + 3.2)]
