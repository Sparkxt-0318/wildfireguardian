"""SIMULATED inputs for field tests A-F, written in exactly the on-disk format the record scripts produce
(run directories readable by wfgvu.replay + trial.json + marks.jsonl [+ rx.jsonl.gz]). Every message carries
`sim: true`, every trial.json `simulated: true`, and every analysis output built from them is watermarked SIMULATED.

These generators exist to exercise the analysis scripts end to end. Their physics is illustrative and stated per
generator; the numbers they produce are NOT measurements and say nothing about how the hardware behaves.
`wfgvu.synth` (DESIGN.md section 4) appeared while this was being written. Its only scenario that matches a field
test is `corner_reflector` (no flame / smoke / mist at the reflector), so it feeds test B's 'nothing' runs through
`synth_b_nothing` (an interop test); everything else here is generated by this module.

All generators are seeded and deterministic.

Flux-disc guard: the A and F runs are passed through the record scripts' own guard (recordkit.DiscGuard) offline
(`apply_disc_guard`), at the simulated laptop receipt times, so a simulated run that heats the disc to 70 C is cut
off, marked and labelled exactly as a recorded one would be. sim_a includes one such run on purpose (a cool-down
run heated too long: stop_reason DISC_OVER_70C), so the "STOPPED: disc 70 C" path of the analysis is exercised.
"""
from __future__ import annotations

import gzip
import json
import math
from pathlib import Path
from typing import Callable, Dict, Iterable, List, Optional, Sequence, Tuple

import numpy as np

from . import common
from .recordkit import DiscGuard
from wfgvu import protocol, recorder

UNIT = "VU-SIM"
SIGMA = 5.670374419e-8
RX_OFFSET = 5000.0          # simulated laptop monotonic = Pi t_mono + RX_OFFSET (+ link delay)


# ---------------------------------------------------------------------------------------------- helpers
class SimRun:
    """Collects protocol messages for one simulated run and writes the run directory."""

    def __init__(self, run_dir, session_id: str):
        self.dir = Path(run_dir)
        self.ctx = protocol.Context(UNIT, session_id, sim=True)
        self.msgs: List[dict] = []
        self.seq: Dict[str, int] = {}
        self.hb_seq: Dict[str, int] = {}
        self.marks: List[dict] = []
        self.rx_lines: List[dict] = []

    def reading(self, sensor: str, t: float, data: dict) -> dict:
        s = self.seq.get(sensor, 0)
        self.seq[sensor] = s + 1
        m = self.ctx.make("reading", sensor=sensor, seq=s, data=data, t_mono=float(t), t_utc=None)
        self.msgs.append(m)
        return m

    def heartbeat(self, sensor: str, t: float, status: str = "ok", detail: str = "", rate_hz=None) -> dict:
        s = self.hb_seq.get(sensor, 0)
        self.hb_seq[sensor] = s + 1
        last = self.seq.get(sensor)
        m = self.ctx.make("heartbeat", sensor=sensor, status=status, detail=detail,
                          last_reading_seq=None if not last else last - 1, rate_hz=rate_hz, seq=s,
                          t_mono=float(t), t_utc=None)
        self.msgs.append(m)
        return m

    def event(self, t: float, kind: str, detail: str = "") -> None:
        self.msgs.append(self.ctx.make("event", kind=kind, detail=detail, t_mono=float(t), t_utc=None))

    def mark(self, kind: str, pi_t: float, note: str = "", **extra) -> None:
        rec = {"t_rx": pi_t + RX_OFFSET, "pi_t_mono": pi_t, "kind": kind, "note": note, "utc": None}
        rec.update(extra)
        self.marks.append(rec)

    def heartbeats_every(self, sensors: Sequence[str], t0: float, t1: float, period: float = 0.5,
                         status_fn: Optional[Callable[[str, float], Tuple[str, str]]] = None) -> None:
        for t in np.arange(t0, t1, period):
            for s in sensors:
                st, det = status_fn(s, float(t)) if status_fn else ("ok", "")
                if st is None:
                    continue
                self.heartbeat(s, float(t), st, det)

    def write(self, trial: Optional[dict], rx_from_msgs: bool = False,
              drop_rx: Optional[Callable[[float], bool]] = None, link_delay_s: float = 0.004,
              info_extra: Optional[dict] = None) -> Path:
        self.dir.mkdir(parents=True, exist_ok=True)
        self.msgs.sort(key=lambda m: m["t_mono"])
        info = {"unit_id": UNIT, "session_id": self.ctx.session_id, "sim": True,
                "recorded_by": "field_tests/simulate.py (SIMULATED)"}
        info.update(info_extra or {})
        recorder.write_session(self.dir, info, self.msgs)
        if trial is None:
            return self.dir
        # unit (server) heartbeats are a separate file in the recorder format
        trial = dict(trial)
        trial.update({"simulated": True, "sim": True, "generator": "field_tests/simulate.py"})
        common.write_json(self.dir / "trial.json", trial)
        with open(self.dir / "marks.jsonl", "w") as fh:
            for m in self.marks:
                fh.write(json.dumps(common.clean(m)) + "\n")
        if rx_from_msgs or self.rx_lines:
            lines = list(self.rx_lines)
            if rx_from_msgs:
                for m in self.msgs:
                    t = float(m["t_mono"]) + RX_OFFSET + link_delay_s
                    if drop_rx is not None and drop_rx(float(m["t_mono"])):
                        continue
                    lines.append({"t_rx": t, "t_mono": float(m["t_mono"]), "type": m["type"],
                                  "sensor": m.get("sensor"), "seq": m.get("seq"), "status": m.get("status"),
                                  "session_id": m["session_id"]})
            lines.sort(key=lambda x: x["t_rx"])
            with gzip.open(self.dir / "rx.jsonl.gz", "wt") as fh:
                for x in lines:
                    fh.write(json.dumps(x) + "\n")
        return self.dir


def apply_disc_guard(run: "SimRun", needs_plate: bool = True, plate_phases: Optional[Sequence[str]] = None,
                     disc_max_c: Optional[float] = None, link_delay_s: float = 0.004,
                     step_s: float = 0.1) -> DiscGuard:
    """Run recordkit.DiscGuard over a simulated run as the record script would (laptop receipt time = Pi t_mono +
    RX_OFFSET + link delay; missing-data check every `step_s`; phase marks switch `plate_phases` on/off). On a stop,
    drop every message and mark after the stop and add the `disc_stop` mark. Returns the guard (annotate the trial
    with guard.annotate(trial)). disc_max_c None = crossing.yaml flux.disc_max_c (70 C)."""
    g = DiscGuard(disc_max_c=disc_max_c, needs_plate=bool(needs_plate) and plate_phases is None)
    run.msgs.sort(key=lambda m: m["t_mono"])
    off = RX_OFFSET + link_delay_s
    marks = sorted(run.marks, key=lambda m: m["pi_t_mono"])
    mi = 0
    t_last = None
    for m in run.msgs:
        t = float(m["t_mono"]) + off
        while mi < len(marks) and float(marks[mi]["pi_t_mono"]) + RX_OFFSET <= t:
            if plate_phases is not None:
                g.set_needs_plate(marks[mi]["kind"] in plate_phases, float(marks[mi]["pi_t_mono"]) + RX_OFFSET)
            mi += 1
        if t_last is not None:
            for tk in np.arange(t_last + step_s, t, step_s):
                if g.check(float(tk)):
                    break
        if g.stop_reason:
            break
        g.on_message(m, t)
        t_last = t
        if g.stop_reason:
            break
    if g.stop_reason:
        t_stop_pi = g.stop_t - off
        run.msgs = [m for m in run.msgs if float(m["t_mono"]) <= t_stop_pi + 1e-9]
        run.marks = [mk for mk in run.marks if float(mk["pi_t_mono"]) <= t_stop_pi]
        run.mark("disc_stop", t_stop_pi, g.stop_detail, stop_reason=g.stop_reason, disc_c=g.stop_c,
                 disc_max_c=g.disc_max_c)
    return g


def tc_data(temp_c: Optional[float], cj_c: float = 25.0, fault=None) -> dict:
    """MAX31855-like reading: 0.25 C hot-junction and 0.0625 C cold-junction quantisation."""
    if fault or temp_c is None:
        return {"temp_c": None, "cj_c": round(cj_c / 0.0625) * 0.0625, "fault": fault}
    return {"temp_c": round(float(temp_c) / 0.25) * 0.25, "cj_c": round(cj_c / 0.0625) * 0.0625, "fault": None}


def write_unit_heartbeats(run_dir, session_id: str, t0: float, t1: float, gaps: Sequence[Tuple[float, float]] = (),
                          period: float = 0.5) -> None:
    """Server ("unit") heartbeats to unit.jsonl.gz, skipping the given (start, end) gaps."""
    ctx = protocol.Context(UNIT, session_id, sim=True)
    with gzip.GzipFile(str(Path(run_dir) / "unit.jsonl.gz"), "wb", mtime=0) as fh:
        k = 0
        for t in np.arange(t0, t1, period):
            if any(a <= t < b for a, b in gaps):
                continue
            m = ctx.make("heartbeat", sensor="unit", status="ok", detail="server alive", last_reading_seq=None,
                         rate_hz=None, seq=k, t_mono=float(t), t_utc=None)
            k += 1
            fh.write((protocol.dumps(m) + "\n").encode())


# ---------------------------------------------------------------------------------------------- test A
A_TRUTH = {"h_w_m2k": 11.0, "eps": 0.95, "alpha": 0.95, "chi_true": 0.08, "gas_flow_l_min": 2.0,
           "lhv_mj_m3": 33.9, "flame_flicker_rel": 0.05, "tc_noise_c": 0.12}


def a_sheet() -> dict:
    return {"heat_source": "Bunsen burner", "gas": "methane", "gas_flow_l_min": A_TRUTH["gas_flow_l_min"],
            "gas_flow_ref": "15 C, 101.325 kPa", "lhv_mj_m3": None, "combustion_efficiency": 1.0,
            "air_hole": "closed", "chi": 0.10, "chi_range": [0.03, 0.20], "flame_diameter_m": 0.02,
            "flame_height_m": 0.12, "plate": {"thickness_m": 0.001, "rho": 8960.0, "cp": 385.0,
                                               "absorptivity": 0.95, "emissivity": 0.95},
            "distances_m": [0.10, 0.15, 0.20, 0.30, 0.40], "repeats": 3, "room_air_c": 21.0}


def _plate_sim(q_fn: Callable[[float], float], t0: float, t1: float, T0_c: float, air_c: float,
               rng: np.random.Generator, dt_out: float = 0.1, sub: int = 10):
    """Plate energy balance m dT/dt = alpha q_inc - h (T-Ta) - eps sigma (T^4-Ta^4), RK4 at dt_out/sub.
    m = rho cp d = 8960*385*0.001 J/m2/K. Returns (t, T_c) sampled every dt_out."""
    m = 8960.0 * 385.0 * 0.001
    h, eps, a = A_TRUTH["h_w_m2k"], A_TRUTH["eps"], A_TRUTH["alpha"]
    ta = air_c + 273.15

    def f(t, T):
        return (a * q_fn(t) * 1000.0 - h * (T - ta) - eps * SIGMA * (T ** 4 - ta ** 4)) / m
    ts = np.arange(t0, t1, dt_out)
    out = np.empty(ts.size)
    T = T0_c + 273.15
    hdt = dt_out / sub
    for i, t in enumerate(ts):
        out[i] = T
        for k in range(sub):
            tt = t + k * hdt
            k1 = f(tt, T); k2 = f(tt + hdt / 2, T + hdt * k1 / 2)
            k3 = f(tt + hdt / 2, T + hdt * k2 / 2); k4 = f(tt + hdt, T + hdt * k3)
            T += hdt * (k1 + 2 * k2 + 2 * k3 + k4) / 6
    return ts, out - 273.15


def _flicker(rng, n, rel, tau_steps=30):
    """Slow multiplicative flame flicker: AR(1) with correlation time tau_steps samples, std `rel`."""
    a = math.exp(-1.0 / tau_steps)
    x = np.zeros(n)
    e = rng.normal(0, rel * math.sqrt(1 - a * a), n)
    for i in range(1, n):
        x[i] = a * x[i - 1] + e[i]
    return 1.0 + x


def sim_a(root, seed: int = 1, distances=(0.10, 0.15, 0.20, 0.30, 0.40), repeats: int = 3, n_cooldown: int = 2,
          background_s: float = 60.0, exposure_s: float = 180.0, cooldown_tail_s: float = 60.0,
          cooldown_s: float = 500.0, stopped_cooldown: bool = True) -> List[Path]:
    """SIMULATED test A. True plate loss h = 11 W/m2K, eps 0.95; Bunsen Q = 2.0 L/min methane x 33.9 MJ/m3
    = 1.13 kW; TRUE radiant fraction 0.08 (the sheet assumes 0.10, so the point-source model over-predicts by 25 %
    on purpose); point-source exposure with 5 % slow flicker; MAX31855 noise 0.12 C, 0.25 C quantisation, 10 Hz.
    Cool-down runs heat the disc with 1.5 kW/m2 for 120 s (peak about 57 C, under the 70 C disc limit). With
    `stopped_cooldown` one extra cool-down run heats at 8 kW/m2 (as the protocol did before the 70 C limit): the
    disc guard stops it at 70 C during the heat phase (stop_reason DISC_OVER_70C, no cooldown mark)."""
    rng = np.random.default_rng(seed)
    root = Path(root)
    sheet = a_sheet()
    q_kw = A_TRUTH["gas_flow_l_min"] / 60000.0 * A_TRUTH["lhv_mj_m3"] * 1000.0
    gate = {"supervisor": "SIMULATED supervisor", "risk_assessment_path": "SIMULATED (no file)",
            "risk_assessment_sha256": "0" * 64}
    dirs = []
    t_base = 1000.0
    k = 0
    for c in range(n_cooldown + (1 if stopped_cooldown else 0)):
        overheat = c == n_cooldown                      # the extra run: heated too hard, stopped by the guard
        sid = "VU-SIM-A-cool-%d" % c
        run = SimRun(root / ("A_cooldown_r%d_SIM%s" % (c + 1, "_overheated" if overheat else "")), sid)
        t0, th = t_base, t_base + 5.0
        tcool = th + 120.0
        tend = tcool + cooldown_s
        air = 21.0 + rng.normal(0, 0.3)
        q_heat = 8.0 if overheat else 1.5
        ts, T = _plate_sim(lambda t, q_heat=q_heat: q_heat if th <= t < tcool else 0.0, t0, tend, air, air, rng)
        T = T + rng.normal(0, A_TRUTH["tc_noise_c"], T.size)
        for t, v in zip(ts, T):
            run.reading("tc_plate", t, tc_data(v))
            run.reading("tc_air", t + 0.03, tc_data(air + rng.normal(0, 0.1)))
        run.heartbeats_every(["tc_plate", "tc_air"], t0, tend)
        run.mark("heat", th); run.mark("cooldown", tcool); run.mark("end", tend - 0.5)
        trial = {"test": "A", "run_id": run.dir.name, "kind": "cooldown", "repeat": c + 1, "distance_m": None,
                 "heat_source": "Bunsen burner (SIMULATED)", "sheet": sheet, "created_utc": "SIM-%03d" % k,
                 "sim_heat_kw_m2": q_heat}
        if overheat:
            trial["notes"] = "SIMULATED: heated at 8 kW/m2 (too hard); the disc guard stops the run at 70 C"
        trial.update(gate)
        apply_disc_guard(run, needs_plate=True).annotate(trial)
        dirs.append(run.write(trial))
        k += 1
        t_base += 2000.0
    for d in distances:
        for rep in range(1, repeats + 1):
            sid = "VU-SIM-A-d%.2f-r%d" % (d, rep)
            run = SimRun(root / ("A_exposure_d%.3f_r%d_SIM" % (d, rep)), sid)
            t0 = t_base
            tb, te = t0 + 2.0, t0 + 2.0 + background_s
            tc = te + exposure_s
            tend = tc + cooldown_tail_s
            air = 21.0 + rng.normal(0, 0.3)
            q0 = A_TRUTH["chi_true"] * q_kw / (4 * math.pi * d ** 2)
            n = int((tend - t0) / 0.1) + 2
            fl = _flicker(rng, n, A_TRUTH["flame_flicker_rel"])
            q_fn = (lambda t, te=te, tc=tc, q0=q0, fl=fl, t0=t0:
                    q0 * fl[min(int((t - t0) / 0.1), n - 1)] if te <= t < tc else 0.0)
            ts, T = _plate_sim(q_fn, t0, tend, air, air, rng)
            T = T + rng.normal(0, A_TRUTH["tc_noise_c"], T.size)
            for t, v in zip(ts, T):
                run.reading("tc_plate", t, tc_data(v))
                run.reading("tc_air", t + 0.03, tc_data(air + rng.normal(0, 0.1)))
            run.heartbeats_every(["tc_plate", "tc_air"], t0, tend)
            run.mark("background", tb); run.mark("exposure", te); run.mark("cooldown", tc)
            run.mark("end", tend - 0.5)
            trial = {"test": "A", "run_id": run.dir.name, "kind": "exposure", "repeat": rep, "distance_m": d,
                     "heat_source": "Bunsen burner (SIMULATED)", "sheet": sheet, "created_utc": "SIM-%03d" % k,
                     "truth_q_kw_m2": q0}
            trial.update(gate)
            apply_disc_guard(run, needs_plate=True).annotate(trial)
            dirs.append(run.write(trial))
            k += 1
            t_base += 2000.0
    return dirs


# ---------------------------------------------------------------------------------------------- test B
B_TRUTH = {"n_bins": 128, "range_res_m": 0.0488, "n_ant": 4, "noise_counts": 40.0, "reflector_amp_2m": 6000.0,
           "flame_phase_step_full_rad": 1.0, "flame_amp_rel_full": 0.05, "flame_loss_full_db": 0.5,
           "flame_width_m": 0.05, "beam_halfwidth_deg": 30.0, "mist_loss_db": 1.5, "mist_amp_rel": 0.03}


def _radar_frame(rng, amp: Dict[int, complex]) -> np.ndarray:
    """One heatmap [bins, ant]: static echoes at bearing 0 (all antennas in phase, so steering = 1) plus complex
    Gaussian noise of B_TRUTH['noise_counts'] per component (int16 quantisation happens in encode_iq)."""
    nb, na, s = B_TRUTH["n_bins"], B_TRUTH["n_ant"], B_TRUTH["noise_counts"]
    x = (rng.normal(0, s, (nb, na)) + 1j * rng.normal(0, s, (nb, na)))
    for b, a in amp.items():
        x[b, :] += a
    return x


def sim_b(root, seed: int = 2, distances=(2.0, 3.0, 4.0, 5.0), duration_s: float = 30.0,
          repeats: Optional[Dict[str, int]] = None, fps: float = 10.0) -> List[Path]:
    """SIMULATED test B (illustrative physics, NOT a radar model validated against hardware):
    - corner reflector at bearing 0, amplitude 6000 counts at 2 m falling as 1/R^2 (radar equation, amplitude),
      leaking -10 dB into the neighbouring bins; two static clutter echoes; complex noise 40 counts per component.
    - flame: frame-to-frame phase random-walk steps of 1.0 rad x c, amplitude flicker 5 % x c and 0.5 dB x c loss on
      bins beyond the flame, where c = flame width (0.05 m) / beam footprint width at the flame distance
      (2 d tan 30 deg) is the fraction of the beam the Bunsen-size flame covers.
    - smoke: no effect at all (the DESIGN assumption, by construction).
    - mist: 1.5 dB loss and 3 % amplitude flicker on bins beyond the mist.
    """
    rng = np.random.default_rng(seed)
    root = Path(root)
    reps = repeats or {"nothing": 3, "flame": 3, "smoke": 2, "mist": 2}
    res = B_TRUTH["range_res_m"]
    gate = {"supervisor": "SIMULATED supervisor", "risk_assessment_path": "SIMULATED (no file)",
            "risk_assessment_sha256": "0" * 64}
    dirs = []
    t_base = 5000.0
    k = 0
    for d in distances:
        b_ref = int(round(d / res))
        a_ref = B_TRUTH["reflector_amp_2m"] * (2.0 / d) ** 2
        clutter = {int(round(1.2 / res)): 900.0 * np.exp(1j * 0.3), int(round(5.9 / res)): 700.0 * np.exp(1j * 2.0)}
        phase0 = rng.uniform(-math.pi, math.pi)
        runs = [("nothing", "baseline", 1)] + [(c, "trial", i + 1) for c in ("nothing", "flame", "smoke", "mist")
                                               for i in range(reps.get(c, 0))]
        for cond, role, rep in runs:
            fd = d / 2.0
            cov = min(1.0, B_TRUTH["flame_width_m"] / (2 * fd * math.tan(math.radians(B_TRUTH["beam_halfwidth_deg"]))))
            run = SimRun(root / ("B_d%.1f_%s_%s_r%d_SIM" % (d, cond, role, rep)), "VU-SIM-B-%03d" % k)
            t0 = t_base
            if role == "baseline":
                phases = [("baseline", t0 + 1.0, t0 + 1.0 + duration_s)]
                t_on, t_off = None, None
                tend = t0 + 2.0 + duration_s
            else:
                t_on, t_off = t0 + 6.0, t0 + 6.0 + duration_s
                phases = [("pre", t0 + 1.0, t_on), ("condition_on", t_on, t_off), ("condition_off", t_off, t_off + 3)]
                tend = t_off + 4.0
            ph_walk = 0.0
            for i, t in enumerate(np.arange(t0, tend, 1.0 / fps)):
                on = t_on is not None and t_on <= t < t_off
                amp = {b: a for b, a in clutter.items()}
                g = 1.0
                if on and cond == "flame":
                    ph_walk += rng.normal(0, B_TRUTH["flame_phase_step_full_rad"] * cov)
                    g = (1 + rng.normal(0, B_TRUTH["flame_amp_rel_full"] * cov)) * \
                        10 ** (-B_TRUTH["flame_loss_full_db"] * cov / 20)
                elif on and cond == "mist":
                    g = (1 + rng.normal(0, B_TRUTH["mist_amp_rel"])) * 10 ** (-B_TRUTH["mist_loss_db"] / 20)
                a = a_ref * g * np.exp(1j * (phase0 + ph_walk))
                amp[b_ref] = a
                amp[b_ref - 1] = a * 0.316
                amp[b_ref + 1] = a * 0.316
                if on and cond in ("flame", "mist"):
                    far = int(round(5.9 / res))
                    if far * res > fd:
                        amp[far] = clutter[far] * g * np.exp(1j * ph_walk)
                x = _radar_frame(rng, amp)
                run.reading("radar", float(t), {"frame": i, "range_res_m": res, "n_bins": B_TRUTH["n_bins"],
                                                "range_profile_db": None, "az_heatmap": protocol.encode_iq(x),
                                                "points": None, "tlv_types": [4], "frame_ok": True})
            run.heartbeats_every(["radar"], t0, tend)
            for kind, ta, _ in phases:
                run.mark(kind, ta)
            run.mark("end", tend - 0.2)
            trial = {"test": "B", "run_id": run.dir.name, "distance_m": d, "condition": cond, "role": role,
                     "repeat": rep, "flame_distance_m": fd, "created_utc": "SIM-%03d" % k,
                     "flame_source": "Bunsen burner (SIMULATED)" if cond == "flame" else "",
                     "flame_kind": "bunsen" if cond == "flame" else None,
                     "bunsen_burner": True if cond == "flame" else None,
                     "truth": {"beam_coverage": cov, "reflector_bin": b_ref}}
            if cond in ("flame", "smoke"):                 # both are gated (a smouldering source still burns)
                trial.update(gate)
            dirs.append(run.write(trial))
            k += 1
            t_base += 100.0
    return dirs


