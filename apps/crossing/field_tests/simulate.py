def sim_d(root, seed: int = 4, faults: Optional[Sequence[str]] = None, tick_s: float = 0.2,
          mark_jitter_s: float = 0.15, latency: Optional[Dict[str, Tuple[float, float]]] = None) -> Path:
    """SIMULATED test D timeline: the app pushes a State every 0.2 s; before each fault the verdict is CROSS FAST
    (as in a sim scenario that allows a crossing), all sensors fresh. At the physical fault time the sensor's
    health flips after a latency drawn from D_LATENCY (entries in `latency` override it, e.g. to show a FAIL row);
    the verdict is CLOSED from the next tick. The operator's mark differs from the physical fault by N(0, 0.15 s),
    except thermal_freeze, whose mark is 1.5-3 s off (the operator cannot see the sim session's T) and whose fault
    time the analysis takes from a simulated `pi/` copy of the thermal frames (4 Hz, identical pixels from the
    freeze on). Restore 8 s later; recovery after 1-3 s (60 s for a power pull). Nothing here is measured: it
    exercises d_failsafe_analyse."""
    from .d_failsafe_analyse import FAULTS, LINK, SENSORS
    rng = np.random.default_rng(seed)
    faults = list(faults or D_LATENCY)
    run_dir = Path(root) / "D_SIM"
    run_dir.mkdir(parents=True, exist_ok=True)
    states, marks = [], []
    t = 100.0
    down: Dict[str, Tuple[float, float]] = {}            # sensor -> (t_down, t_up)

    def state_at(tt: float) -> dict:
        fresh = {s: True for s in SENSORS}
        link = True
        for f, (a, b) in down.items():
            if a <= tt < b:
                sens = FAULTS[f].sensors
                if LINK in sens:
                    link = False
                    fresh = {s: False for s in SENSORS}
                else:
                    for s in sens:
                        fresh[s] = False
        bad = [s for s, v in fresh.items() if not v]            # every sensor is required (decision D1)
        if not link:
            return {"verdict": "CLOSED", "reasons": ["LINK_DOWN"], "link": False, "fresh": fresh, "sim": True}
        if bad:
            return {"verdict": "CLOSED", "reasons": ["SENSOR_NOT_FRESH:%s" % s for s in bad], "link": True,
                    "fresh": fresh, "sim": True}
        return {"verdict": "CROSS FAST", "reasons": [], "link": True, "fresh": fresh, "sim": True}

    schedule = []
    lat = dict(D_LATENCY, **(latency or {}))
    for f in faults:
        t_phys = t + 10.0
        lo, hi = lat[f]
        t_flip = t_phys + rng.uniform(lo, hi)
        t_restore = t_phys + 8.0
        rec = 60.0 if f == "pi_power" else rng.uniform(1.0, 3.0)
        down[f] = (t_flip, t_restore + rec)
        schedule.append((f, t_phys, t_restore))
        t = t_restore + rec + 5.0
    for tt in np.arange(100.0, t, tick_s):
        s = state_at(float(tt))
        s["t_rx"] = float(tt) + 0.01
        states.append(s)
    frames = []                                              # (t_rx, msg) of the simulated pi/ thermal copy
    for f, t_phys, t_restore in schedule:
        off = rng.normal(0, mark_jitter_s)
        if f == "thermal_freeze":
            off = float(rng.choice([-1.0, 1.0]) * rng.uniform(1.5, 3.0))
            for k, tt in enumerate(np.arange(t_phys - 6.0, t_restore, 0.25)):
                frozen = tt >= t_phys
                kk = int(np.floor((t_phys - (t_phys - 6.0)) / 0.25 - 1e-9)) if frozen else k
                img = np.full((6, 8), 290.0) + (kk % 7) * 0.1 + np.arange(48).reshape(6, 8) * 0.01
                frames.append((float(tt) + 0.02, {"type": "reading", "sensor": "thermal", "seq": k,
                                                  "t_mono": float(tt) - 50.0, "sim": True,
                                                  "data": protocol.encode_thermal(img)}))
        marks.append({"t_rx": t_phys + off, "kind": "fault_inject", "fault": f,
                      "sensors": list(FAULTS[f].sensors), "note": FAULTS[f].inject, "pi_t_mono": None})
        marks.append({"t_rx": t_restore, "kind": "fault_restore", "fault": f, "note": FAULTS[f].restore,
                      "pi_t_mono": None})
    with gzip.open(run_dir / "states.jsonl.gz", "wt") as fh:
        for s in states:
            fh.write(json.dumps(s) + "\n")
    with open(run_dir / "marks.jsonl", "w") as fh:
        for m in sorted(marks, key=lambda m: m["t_rx"]):
            fh.write(json.dumps(m) + "\n")
    if frames:
        (run_dir / "pi").mkdir(exist_ok=True)
        with gzip.open(run_dir / "pi" / "rx.jsonl.gz", "wt") as fr, \
                gzip.open(run_dir / "pi" / "thermal.jsonl.gz", "wt") as fth:
            for t_rx, m in frames:
                fr.write(json.dumps({"t_rx": t_rx, "t_mono": m["t_mono"], "type": "reading", "sensor": "thermal",
                                     "seq": m["seq"], "status": None, "session_id": "SIM"}) + "\n")
                fth.write(json.dumps(m) + "\n")
    common.write_json(run_dir / "trial.json", {"test": "D", "run_id": "D_SIM", "faults": faults, "simulated": True,
                                               "generator": "field_tests/simulate.py", "latency_model": lat})
    return run_dir


