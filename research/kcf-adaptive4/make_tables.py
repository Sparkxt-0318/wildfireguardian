#!/usr/bin/env python3
"""Markdown tables for RESULTS.md from derived/*.json (no number is typed by hand).

    python make_tables.py > derived/tables.md
"""
import json

import pandas as pd

import lib4 as L

D = L.HERE / "derived"
ORDER = ["FIXED", "QUANTILE", "RULE", "RULE10", "BASE-gust", "BASE-850", "ONEK", "NONE", "TARGETED", "ALL"]
LABEL = {"FIXED": "FIXED", "QUANTILE": "QUANTILE (kcf-adaptive2)", "RULE": "RULE (k = 0.10 on gust, not calibrated)",
         "RULE10": "RULE rescaled to 10%", "BASE-gust": "BASE-gust (k learned)", "BASE-850": "BASE-850 (k learned)",
         "ONEK": "BASE, one k for all leads", "ONEK-gust": "BASE-gust, one k for all leads",
         "ONEK-850": "BASE-850, one k for all leads", "NONE": "NONE (= primary BASE, no update)",
         "TARGETED": "TARGETED (blamed term only)", "ALL": "ALL (every term, every hour)"}


def pc(x):
    return f"{100 * x:.1f}%"


def main_table(res, title, lead=5):
    print(f"\n### {title}\n")
    print("| Model | Miss, 95% interval | Area (km2) | Area / FIXED (95%) | Area read at exactly 10% miss | Reach error (km) | Mean shortfall on a miss (km) | Mean excess on a hold (km) | Fires | Hours |")
    print("|---|---|---|---|---|---|---|---|---|---|")
    for m in [x for x in ORDER + sorted(set(res) - set(ORDER)) if x in res]:
        r = res[m][lead - 1]
        ratio = f"{r['area_ratio']:.2f} ({r['area_ratio_lo']:.2f} to {r['area_ratio_hi']:.2f})" if "area_ratio" in r else "1.00"
        a10 = r.get("area_at_10")
        a10 = "-" if a10 is None or a10 != a10 else f"{a10:.1f}"
        print(f"| {LABEL.get(m, m)} | {pc(r['miss'])} ({pc(r['miss_lo'])} to {pc(r['miss_hi'])}) | {r['area']:.1f} | {ratio} | "
              f"{a10} | {r['pinball']:.3f} | {r['shortfall']:.2f} | {r['excess']:.2f} | {r['n_fires']} | {r['n_hours']} |")


def lead_table(res, title, models, key="pinball", fmt="{:.3f}"):
    print(f"\n### {title}\n")
    print("| Model | " + " | ".join(f"{h} h" for h in range(1, 9)) + " |")
    print("|---|" + "---|" * 8)
    for m in models:
        if m in res:
            print(f"| {LABEL.get(m, m)} | " + " | ".join(fmt.format(res[m][h][key]) for h in range(8)) + " |")


def att_table(tab, title, key=5):
    if key not in tab and str(key) not in tab:
        print(f"\n### {title}\n\nNo missed hour.\n")
        return
    t = tab.get(key, tab.get(str(key)))
    print(f"\n### {title}\n")
    print(f"{t['n_misses']} missed issue hours on {t['n_fires']} fires; missed area {t['missed_area_km2']:.0f} km2; "
          f"truth wind available for {pc(t['wind_truth_share'])} of them; start evidence available for "
          f"{pc(t['start_measurable_share'])}.\n")
    print("| Term | Share of misses (95%) | Share of missed area (95%) | Fixed by swapping this term alone (95%) |")
    print("|---|---|---|---|")
    for term in ("wind", "k", "start", "timing", "unexplained"):
        a, b = t["share_of_misses"][term], t["share_of_missed_area"][term]
        c = t["single_swap_fix_rate"].get(term)
        cs = f"{pc(c['value'])} ({pc(c['lo'])} to {pc(c['hi'])})" if c else "-"
        print(f"| {term} | {pc(a['value'])} ({pc(a['lo'])} to {pc(a['hi'])}) | {pc(b['value'])} ({pc(b['lo'])} to {pc(b['hi'])}) | {cs} |")


def main():
    dev = json.loads((D / "dev_base.json").read_text())
    print("# Tables (generated by make_tables.py)")
    main_table(dev["summary"], "CA-DEV (16 fires, cross-validated by fire), 5 h")
    lead_table(dev["summary"], "CA-DEV, reach error (km) by lead", ["FIXED", "QUANTILE", "BASE-gust", "BASE-850", "ONEK-gust"])
    lead_table(dev["summary"], "CA-DEV, miss rate by lead", ["FIXED", "QUANTILE", "RULE", "BASE-gust", "BASE-850", "ONEK-gust"], "miss", "{:.3f}")
    print("\nwind choice:", dev["wind_choice"])
    print("\nk_h by fold (BASE-gust):", {k: [round(x, 4) for x in v["BASE-gust"]] for k, v in dev["params"].items()})
    att = json.loads((D / "attribution_ca_dev.json").read_text())
    att_table(att, "Attribution, CA-DEV, 5 h", "5")
    att_table(att, "Attribution, CA-DEV, all leads", "all")
    if (D / "dev_grid.json").exists():
        g = json.loads((D / "dev_grid.json").read_text())
        print("\n### Correction settings grid, CA-DEV, 5 h reach error (km); L = lookback h, H = half-life h\n")
        print("| Arm | " + " | ".join(f"L {a}, H {b}" for a in (6, 12, 24) for b in (3, 6, 12)) + " |")
        print("|---|" + "---|" * 9)
        for arm in ("TARGETED", "ALL"):
            print(f"| {arm} | " + " | ".join(f"{g[arm][f'{a},{b}']['pinball5']:.4f}" for a in (6, 12, 24) for b in (3, 6, 12)) + " |")
        print("\nkept:", json.loads((D / "kept.json").read_text()))
    if not (D / "numbers_final.json").exists():
        return
    N = json.loads((D / "numbers_final.json").read_text())
    for s, t in (("CA-HELD", "CA-HELD (12 fires, fitted on the 16 development fires), 5 h"),
                 ("KR", "Korea (12 fires, leave-one-fire-out), 5 h")):
        main_table(N[s], t)
        lead_table(N[s], f"{s}, reach error (km) by lead", ["FIXED", "QUANTILE", "RULE", "NONE", "TARGETED", "ALL"])
        lead_table(N[s], f"{s}, miss rate by lead", ["FIXED", "QUANTILE", "RULE", "NONE", "TARGETED", "ALL"], "miss")
        lead_table(N[s], f"{s}, area (km2) by lead", ["FIXED", "QUANTILE", "RULE", "NONE", "TARGETED", "ALL"], "area", "{:.1f}")
    print("\n### Target A: 25 March 2025, 09 to 20 KST, 5 h\n")
    print("| Model | Held of 12 | Largest margin (km) | Mean flagged area (km2, cap 60 km) | Held of all scored hours that day |")
    print("|---|---|---|---|---|")
    for m in [x for x in ORDER if x in N["A"]["models"]]:
        a = N["A"]["models"][m]
        print(f"| {LABEL.get(m, m)} | {a['held']} | {a['max_margin_km']:.1f} | {a['mean_area_km2']:.0f} | {a['held_all_day']} of {a['of_all_day']} |")
    d = pd.read_csv(D / "mar25.csv")
    print("\n### 25 March 2025 hour by hour (5 h lead; M = missed, h = held; margins in km)\n")
    cols = ["FIXED", "QUANTILE", "RULE", "NONE", "TARGETED", "ALL"]
    print("| KST | reach | fc gust (m/s) | ERA5 gust (m/s) | " + " | ".join(cols) + " | blamed | k mult | wind mult | matured misses |")
    print("|---|---|---|---|" + "---|" * len(cols) + "---|---|---|---|")
    for r in d.itertuples():
        if r.reach5_km != r.reach5_km:
            continue
        cells = " | ".join(f"{getattr(r, c.replace('-', '_')):.1f} {'**M**' if r.reach5_km > getattr(r, c.replace('-', '_')) else 'h'}" for c in cols)
        print(f"| {int(r.kst):02d} | {r.reach5_km:.1f} | {r.fc_gust_ms:.1f} | {r.era5_gust_ms:.1f} | {cells} | {r.T_blamed} | {r.T_k_mult:.2f} | {r.T_wind_mult:.2f} | {int(r.T_matured_misses)} |")
    print("\n### Target B\n\n", N["B"])
    print("\n### Target C: reach error difference at each lead (km; negative = the first is better), fire bootstrap\n")
    for reg in ("POOLED", "CA-HELD", "KR"):
        print(f"\n**{reg}**\n\n| Comparison | " + " | ".join(f"{h} h" for h in range(1, 9)) + " | relative at 5 h |")
        print("|---|" + "---|" * 9)
        for k, v in N["C"][reg].items():
            print(f"| {k} | " + " | ".join(f"{v[str(h)]['diff']:+.3f} ({v[str(h)]['lo']:+.3f} to {v[str(h)]['hi']:+.3f})" for h in range(1, 9)) + f" | {100 * v['rel5']:+.1f}% |")
    print("\n### Error growth: slope of reach error against lead (km per hour of lead)\n")
    print("| Set | Model | Slope | Change against NONE (95%) |")
    print("|---|---|---|---|")
    for reg in ("POOLED", "CA-HELD", "KR"):
        G = N["growth"][reg]
        for m in ("FIXED", "QUANTILE", "RULE", "NONE", "TARGETED", "ALL"):
            ch = G.get(f"change_{m}_vs_NONE")
            cs = f"{100 * ch['rel']:+.1f}% ({100 * ch['lo']:+.1f}% to {100 * ch['hi']:+.1f}%)" if ch else "-"
            print(f"| {reg} | {LABEL.get(m, m)} | {G[m]['slope_km_per_h']:.4f} | {cs} |")
    nr = N["D"]["norun"]
    print(f"\n### Target D: Korean fire-days ({nr['n_fire_days']} with an eligible 5 h hour; {nr['n_run']} with a run, {nr['n_norun']} without)\n")
    print("| Model | Area on no-run fire-days (km2) | Miss on no-run fire-days | Area on run fire-days (km2) |")
    print("|---|---|---|---|")
    for m in [x for x in ORDER if x in nr["models"]]:
        v = nr["models"][m]
        print(f"| {LABEL.get(m, m)} | {v['area_norun']:.1f} | {pc(v['miss_norun'])} | {v['area_run']:.1f} |")
    att_table(N["attribution_kr"]["choi"], "Attribution, Korea, Choi hours, 5 h (start not measurable)", "5")
    att_table(N["attribution_kr"]["choi"], "Attribution, Korea, Choi hours, all leads", "all")
    att_table(N["attribution_kr"]["det"], "Attribution, 25 March detection hours, 5 h", "5")
    att_table(N["attribution_kr"]["det"], "Attribution, 25 March detection hours, all leads", "all")
    att_table(N["attribution_ca_held"], "Attribution, CA-HELD, 5 h", "5")
    print("\n### Term blamed by the online loop (issue hours)\n\n", N["online_blame"])
    print("\n### Expected-error calibration: share of scored rows with reach - margin above the stated quantile\n")
    for s, c in N["expected_error_calibration"].items():
        print(f"\n**{s}**\n\n| Quantile | nominal | all leads (95%) | " + " | ".join(f"{h} h" for h in range(1, 9)) + " |")
        print("|---|---|---|" + "---|" * 8)
        for q, v in c.items():
            a = v["all_leads"]
            print(f"| {q} | {pc(v['nominal'])} | {pc(a['exceed'])} ({pc(a['lo'])} to {pc(a['hi'])}) | "
                  + " | ".join(pc(v[str(h)]["exceed"]) if str(h) in v else "-" for h in range(1, 9)) + " |")
    print("\nparams (k_h NONE, kappa TARGETED/ALL, wind scale), CA-HELD fit:")
    p = N["params"]["CA-HELD"]["final_ca"]
    for k in ("NONE", "TARGETED", "ALL", "WSCALE", "FIXED"):
        print(" ", k, [round(x, 4) for x in p[k]])
    print("  ONEK", round(p["ONEK"], 4))


if __name__ == "__main__":
    main()
