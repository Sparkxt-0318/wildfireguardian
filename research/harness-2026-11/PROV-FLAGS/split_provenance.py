"""Split Richard's verified F-3.1 deadline provenance file into one planner file per cached scenario.

Source: research/harness-2026-11/F-3.1/results/DEADLINE_PROVENANCE_1h.json at commit f0577de on
claude/f31-deadline-field (schema wfg.f31.deadline_provenance/1; verified by Owen, PASS WITH NOTES, 2026-11-12;
sha256 3f558d92c36417f39d26043d8682485f3b3d24f7bd74032c78b5a1eb9414f558).

Each output (planner/public/data/provenance/<region>__<input>.json) carries the identity of the cache it was computed
on (path and sha256 from planner/cache/INDEX.json), so the planner can refuse a file that does not belong to the
cache on screen. Usage (Python 3.12, from the repository root):
  git show f0577de:research/harness-2026-11/F-3.1/results/DEADLINE_PROVENANCE_1h.json > /tmp/prov.json
  python3.12 research/harness-2026-11/PROV-FLAGS/split_provenance.py /tmp/prov.json
"""
import hashlib
import json
import sys
from pathlib import Path

SOURCE = {
    "schema": "wfg.f31.deadline_provenance/1",
    "commit": "f0577de735ef7f699eec360a65b4404ffc270435",
    "path": "research/harness-2026-11/F-3.1/results/DEADLINE_PROVENANCE_1h.json",
    "sha256": "3f558d92c36417f39d26043d8682485f3b3d24f7bd74032c78b5a1eb9414f558",
    "verified": "Owen (verifier), PASS WITH NOTES, 2026-11-12: regenerated byte-for-byte equivalent, 530/530 records",
}
HORIZON_S = 3600


def compact(iso: str) -> str:
    return iso.replace("-", "").replace(":", "")


def main(src: str) -> None:
    raw = Path(src).read_bytes()
    if hashlib.sha256(raw).hexdigest() != SOURCE["sha256"]:
        sys.exit("source file sha256 differs from the verified one")
    doc = json.loads(raw)
    if doc.get("schema") != SOURCE["schema"]:
        sys.exit("unexpected schema")
    root = Path(__file__).resolve().parents[3]
    index = json.loads((root / "planner/cache/INDEX.json").read_text())
    entries = index["entries"] if isinstance(index, dict) else index
    out_dir = root / "planner/public/data/provenance"
    out_dir.mkdir(parents=True, exist_ok=True)
    by_cache: dict[str, dict] = {}
    for r in doc["records"]:
        by_cache.setdefault(r["cache"], {})[r["origin_id"]] = {k: v for k, v in r.items() if k not in ("cache", "origin_id")}
    written = []
    for e in entries:
        cache_path = f"planner/cache/{e['path']}"
        recs = by_cache.get(cache_path)
        if recs is None:
            continue
        out = {
            "schema": "wfg.planner.deadline_provenance/1",
            "source": SOURCE,
            "time_base": doc["time_base"],
            "horizon_s": HORIZON_S,
            "labels": doc["labels"],
            "region_id": e["region_id"],
            "input_time": e["input_time"],
            "cache": {"path": e["path"], "sha256": e["sha256"]},
            "records": dict(sorted(recs.items())),
        }
        name = f"{e['region_id']}__{compact(e['input_time'])}.json"
        (out_dir / name).write_text(json.dumps(out, ensure_ascii=False, indent=1) + "\n")
        written.append((name, len(recs)))
    for n, c in written:
        print(n, c)
    print("total", sum(c for _, c in written))


if __name__ == "__main__":
    main(sys.argv[1])
