"""Supporting tables for RESULTS.md (derived/tables.md) and the numbers file (numbers.json)."""
import json
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats

D = Path(__file__).resolve().parent / "derived"
m = json.load(open(D / "measure.json")); f = json.load(open(D / "fit.json")); t = json.load(open(D / "tests.json"))
sp = pd.read_csv(D / "spots_all.csv"); ir = pd.read_csv(D / "airir_dixie.csv"); t3 = pd.read_csv(D / "test3_closures.csv")
L = []
def _fmt(v):
    if isinstance(v, (float, np.floating)):
        return "" if not np.isfinite(v) else f"{v:.4g}"
    if isinstance(v, (list, tuple)):
        return "[" + ", ".join(_fmt(x) for x in v) + "]"
    return str(v)


def table(title, df):
    head = "| " + " | ".join(map(str, df.columns)) + " |\n|" + "---|" * len(df.columns) + "\n"
    body = "".join("| " + " | ".join(_fmt(v) for v in r) + " |\n" for r in df.itertuples(index=False))
    L.append(f"\n**{title}**\n\n" + head + body)
# step 2
rows = []
for r in m:
    if "by_gust" not in r and r.get("region") != "AIRIR_Dixie":
        continue
    if r.get("region") == "AIRIR_Dixie":
        continue
    rows.append({k: r.get(k) for k in ("region", "confirmed_only", "n", "fires_with", "fire_hours", "per_100_fire_hours",
                                        "dist_km_q50", "dist_km_q90", "dist_km_max", "beyond_5km", "down", "cross", "up",
                                        "down_minus_up", "share_down", "fc_gust_q50", "era5_ws_q50", "single_pixel_share",
                                        "night_share", "ridge_crossing_share", "elev_change_m_q50")})
table("Step 2: candidate spots by region (CA = GOFER + VIIRS burned set; CAV = VIIRS alone, sensitivity; KR = VIIRS; DET = VIIRS + Himawari, KFS_01)", pd.DataFrame(rows))
g = []
for r in m:
    if r.get("region") in ("CA", "CAV", "KR") and r.get("confirmed_only"):
        for k, v in r["by_gust"].items():
            g.append(dict(region=r["region"], gust=k, **v))
table("Step 2: confirmed spots by forecast gust band, downwind and upwind counts", pd.DataFrame(g))
cls = pd.cut(ir.area_ha, [0, 1, 10, 100, 1e9], labels=["<1 ha", "1-10 ha", "10-100 ha", ">100 ha"])
a = []
for k, gg in ir.groupby(cls, observed=False):
    n, s = len(gg), int(gg.seen_viirs.sum())
    lo, hi = (stats.beta.ppf(0.025, s, n - s + 1) if s else 0.0, stats.beta.ppf(0.975, s + 1, n - s) if s < n else 1.0)
    a.append(dict(area=str(k), polygons=n, seen_by_viirs=s, share=s / n if n else np.nan, ci_lo=lo, ci_hi=hi,
                  near_gofer=int(gg.seen_gofer.sum()), median_dist_km=gg.dist_main_km.median()))
table("Satellite detection of detached airborne-IR heat polygons, Dixie 2021 (19 nights)", pd.DataFrame(a))
# step 3
c = f["ca_fit"]
table("Step 3: fit on CA-DEV (cloglog; 1,000 fire-bootstrap resamples)",
      pd.DataFrame(dict(term=c["names"], estimate=c["beta"], lo95=c["ci"][0], hi95=c["ci"][1])))
table("Step 3: fitted P(lit by a spot within 5 h), downwind cell, by forecast gust and distance",
      pd.DataFrame(f["P_grid_5h_downwind"]).drop(columns="cells_per_ha"))
table("Step 3: calibration on CA-HELD by decile of predicted P (fire-weighted)", pd.DataFrame(f["calib_ca_held"]))
vp = pd.DataFrame(f["vs_published"]).T.reset_index().rename(columns={"index": "spots"})
table("Step 3: observed confirmed California spots against the published reference (Albini 1983 maximum; lognormal sigma 0.8, median = Albini max / e^(2.326 sigma), 10 MW/m, 10 m cover)", vp)
# step 5
for reg, tab in t["test2"].items():
    df = pd.DataFrame(tab).drop(columns=["ratio_area_vs_FIXED"], errors="ignore")
    table(f"Test 2: {reg}, 5 h, every margin calibrated to 10% on its training fires", df)
table("Test 1: 25 March 2025, 09-20 KST", pd.DataFrame(t["test1"]).drop(columns="per_hour"))
t4 = pd.DataFrame({k: v for k, v in t["test4"].items() if isinstance(v, dict)}).T.reset_index().rename(columns={"index": "set"})
table("Test 4: kcf-adaptive4 misses at 5 h left unexplained by its four terms", t4)
table("Test 3: road closures of 25 March", t3)
(D / "tables.md").write_text("# kcf-spot supporting tables (generated by make_tables.py)\n" + "".join(L))
# numbers
ca = [r for r in m if r.get("region") == "CA" and r.get("confirmed_only")][0]
nums = dict(
    ca_confirmed=ca["n"], ca_candidates=[r for r in m if r.get("region") == "CA" and not r.get("confirmed_only")][0]["n"],
    ca_down=ca["down"], ca_up=ca["up"], ca_down_minus_up=ca["down_minus_up"], ca_down_minus_up_95=ca["down_minus_up_95"],
    ca_per100h=ca["per_100_fire_hours"], ca_bg_corrected_per100h=100 * ca["down_minus_up"] / ca["fire_hours"],
    ca_dist_q50=ca["dist_km_q50"], ca_dist_q90=ca["dist_km_q90"],
    viirs_seen_lt10ha=float(ir[ir.area_ha < 10].seen_viirs.mean()), viirs_n_lt10ha=int((ir.area_ha < 10).sum()),
    b2_U=c["beta"][2], b2_U_ci=[c["ci"][0][2], c["ci"][1][2]], b1=c["beta"][1], b1_ci=[c["ci"][0][1], c["ci"][1][1]],
    road_P8_max_25mar=float(pd.read_csv(D / "roadlayer_spot_20250325_summary.csv").P8_max.max()))
json.dump(nums, open(D.parent / "numbers.json", "w"), indent=1, default=float)
print(json.dumps(nums, indent=1, default=float))
